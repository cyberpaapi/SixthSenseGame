"use strict";
const assert = require("node:assert/strict");
const streak = require("./daily-streak");
const now = Date.parse("2026-10-14T15:00:00Z");
let stats = { currentStreak: 6, lastWinDate: "2026-10-13", maxStreak: 6, lastDailyRewardStreak: 0 };
assert.equal(streak.snapshot(stats, now).deadline, Date.parse("2026-10-15T00:00:00Z"));
assert.equal(streak.win(stats, now), true);
assert.equal(stats.currentStreak, 7);
assert.equal(streak.snapshot(stats, now).deadline, Date.parse("2026-10-16T00:00:00Z"));
assert.equal(streak.win(stats, now), false, "same-day replay cannot extend a streak");
for (let day = 1; day <= 400; day++) streak.win(stats, now + day * 86400000);
assert.equal(stats.currentStreak, 407, "streak has no seven-day cap");
assert.equal(stats.maxStreak, 407);
stats.lastDailyRewardStreak = 406;
assert.equal(streak.expire(stats, now + 402 * 86400000), true);
assert.equal(stats.currentStreak, 0);
assert.equal(stats.lastDailyRewardStreak, 0, "new runs can earn their own seven-day bonus");
streak.win(stats, now + 402 * 86400000);
assert.equal(stats.currentStreak, 1);
assert.equal(stats.maxStreak, 407);
assert.deepEqual(streak.snapshot({ currentStreak: 15, lastWinDate: "2026-10-12" }, now), { count: 0, deadline: 0 });
assert.deepEqual(streak.snapshot({ currentStreak: 15, lastWinDate: "2026-10-15" }, now), { count: 0, deadline: 0 });
assert.deepEqual(streak.snapshot({ currentStreak: 0, lastWinDate: "2026-10-13" }, now), { count: 0, deadline: 0 });
assert.deepEqual(streak.snapshot({ currentStreak: 15, lastWinDate: "invalid" }, now), { count: 0, deadline: 0 });
assert.equal(streak.snapshot({ currentStreak: 9, lastWinDate: "2026-10-13" }, Date.parse("2026-10-15T00:00:00Z")).count, 0);
console.log("Daily streak policy passed: uncapped progression, UTC boundaries, duplicates, broken-run bonuses and inactive reminders.");
